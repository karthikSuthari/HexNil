    private List<String> identifyDataLimitations(List<BatterySnapshot> snapshots,
                                                  List<ChargingSession> sessions,
                                                  List<DrainEvent> drainEvents) {
        List<String> limitations = new ArrayList<>();
        
        if (snapshots.size() < 200) {
            limitations.add("Limited snapshot history - accuracy improves with more data");
        }
        
        if (sessions.size() < 10) {
            limitations.add("Limited charging sessions - charging behavior analysis may be incomplete");
        }
        
        if (drainEvents.size() < 20) {
            limitations.add("Limited drain events - drain pattern analysis may be incomplete");
        }
        
        // Check for data gaps
        if (!snapshots.isEmpty()) {
            List<BatterySnapshot> sorted = new ArrayList<>(snapshots);
            sorted.sort((a, b) -> Long.compare(a.timestamp, b.timestamp));
            
            for (int i = 1; i < sorted.size(); i++) {
                long gap = sorted.get(i).timestamp - sorted.get(i-1).timestamp;
                if (gap > TimeUnit.HOURS.toMillis(2)) {
                    limitations.add("Data gaps detected - some periods have missing readings");
                    break;
                }
            }
        }
        
        return limitations;
    }
    
    private double calculateOverallConfidence(List<AIInference> inferences,
                                               Map<String, Object> deterministicData) {
        if (inferences.isEmpty()) {
            return 0.3;  // Base confidence for deterministic only
        }
        
        double totalConfidence = 0;
        int count = 0;
        
        for (AIInference inf : inferences) {
            if (inf.meetsMinimumConfidence()) {
                totalConfidence += inf.getConfidenceScore();
                count++;
            }
        }
        
        if (count == 0) {
            return 0.4;
        }
        
        // Average confidence with penalty for few inferences
        double avgConfidence = totalConfidence / count;
        double coverageFactor = Math.min(1.0, count / 5.0);  // Bonus for coverage
        
        return avgConfidence * (0.8 + 0.2 * coverageFactor);
    }
    
    private double getDouble(Map<String, Object> map, String key, double defaultValue) {
        Object value = map.get(key);
        if (value instanceof Number) {
            return ((Number) value).doubleValue();
        }
        return defaultValue;
    }
    
    private boolean getBoolean(Map<String, Object> map, String key, boolean defaultValue) {
        Object value = map.get(key);
        if (value instanceof Boolean) {
            return (Boolean) value;
        }
        return defaultValue;
    }
