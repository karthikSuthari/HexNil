    /**
     * Infer drain anomalies.
     */
    private AIInference inferDrainAnomalies(List<DrainEvent> drainEvents,
                                             List<BatterySnapshot> snapshots,
                                             Map<String, Object> deterministicData) {
        
        List<String> evidence = new ArrayList<>();
        List<String> caveats = new ArrayList<>();
        double confidenceScore = 0.5;
        
        @SuppressWarnings("unchecked")
        Map<String, Object> drainStats = (Map<String, Object>) deterministicData.get("drain_rate_stats");
        
        if (drainStats == null && drainEvents.isEmpty()) {
            return new AIInference(
                    "DRAIN_ANOMALIES",
                    "Insufficient drain data for anomaly detection",
                    0.3,
                    evidence,
                    List.of("No drain events recorded"),
                    "Requires drain event data",
                    false
            );
        }
        
        if (drainStats != null) {
            double meanDrain = getDouble(drainStats, "mean", 0);
            double maxDrain = getDouble(drainStats, "max", 0);
            double stdDev = getDouble(drainStats, "standard_deviation", 0);
            
            evidence.add("Average drain rate: " + String.format("%.1f%%/hour", meanDrain));
            evidence.add("Maximum drain rate: " + String.format("%.1f%%/hour", maxDrain));
            evidence.add("Drain variability (std dev): " + String.format("%.1f", stdDev));
            
            // Detect anomalies based on statistical outliers
            String anomalyAssessment;
            if (maxDrain > meanDrain + 3 * stdDev && stdDev > 2) {
                anomalyAssessment = "ANOMALOUS drain events detected - maximum drain rate is a " +
                        "significant outlier suggesting app misbehavior or background activity";
                confidenceScore = 0.80;
                caveats.add("Anomalies may be legitimate heavy usage");
            } else if (maxDrain > meanDrain * 2 && maxDrain > 15) {
                anomalyAssessment = "Elevated drain events observed - some periods show " +
                        "unusually high consumption";
                confidenceScore = 0.70;
            } else if (meanDrain > 8) {
                anomalyAssessment = "Overall high drain rate - may indicate battery-intensive " +
                        "apps or poor signal conditions";
                confidenceScore = 0.75;
                caveats.add("High drain may be normal for heavy usage");
            } else {
                anomalyAssessment = "No significant drain anomalies detected - consumption " +
                        "patterns appear normal";
                confidenceScore = 0.80;
            }
            
            return new AIInference(
                    "DRAIN_ANOMALIES",
                    anomalyAssessment,
                    confidenceScore,
                    evidence,
                    caveats,
                    "Statistical analysis of drain rate distribution for outliers",
                    true
            );
        }
        
        return new AIInference(
                "DRAIN_ANOMALIES",
                "Drain pattern analysis inconclusive",
                0.4,
                evidence,
                List.of("Limited statistical data"),
                "Requires more drain events",
                false
        );
    }
    
