    /**
     * Synthesize all inferences into a root cause analysis.
     * This is where AI combines multiple signals into actionable insight.
     */
    private RootCauseAnalysis synthesizeRootCause(List<AIInference> inferences,
                                                   Map<String, Object> deterministicData) {
        
        if (inferences.isEmpty()) {
            return new RootCauseAnalysis(
                    "INSUFFICIENT_DATA",
                    0.0,
                    new ArrayList<>(),
                    new ArrayList<>(),
                    "Unable to determine root cause - insufficient data for analysis",
                    "No inferences could be made with sufficient confidence",
                    List.of("Continue collecting battery data for at least 24 hours"),
                    List.of("Review data collection coverage"),
                    List.of("Use device normally to generate representative data"),
                    deterministicData
            );
        }
        
        // Find highest confidence issues
        List<AIInference> significantInferences = new ArrayList<>();
        AIInference primaryIssue = null;
        double highestConfidence = 0;
        
        for (AIInference inf : inferences) {
            if (inf.meetsMinimumConfidence()) {
                significantInferences.add(inf);
                if (inf.getConfidenceScore() > highestConfidence) {
                    highestConfidence = inf.getConfidenceScore();
                    primaryIssue = inf;
                }
            }
        }
        
        // Build root cause
        String rootCause;
        String explanation;
        String technicalDetails;
        List<String> contributing = new ArrayList<>();
        List<String> recommendations = new ArrayList<>();
        List<String> engineerActions = new ArrayList<>();
        List<String> userActions = new ArrayList<>();
        
        if (primaryIssue == null) {
            rootCause = "NO_SIGNIFICANT_ISSUES";
            explanation = "No significant battery issues detected based on available data.";
            technicalDetails = "All metrics within normal parameters.";
            recommendations.add("Continue normal usage");
            userActions.add("No action required at this time");
        } else {
            // Determine root cause based on primary issue type
            switch (primaryIssue.getInferenceType()) {
                case "THERMAL_STRESS":
                    rootCause = "THERMAL_DEGRADATION";
                    explanation = "Thermal stress is the primary factor affecting battery " +
                            "performance. High temperatures accelerate chemical degradation.";
                    technicalDetails = primaryIssue.getStatement();
                    recommendations.add("Reduce heavy processing tasks during charging");
                    recommendations.add("Ensure adequate device ventilation");
                    engineerActions.add("Review thermal throttling thresholds");
                    engineerActions.add("Check thermal paste/cooling system integrity");
                    userActions.add("Avoid using device while charging if it gets hot");
                    userActions.add("Remove case during heavy gaming");
                    break;
                    
                case "DRAIN_ANOMALIES":
                    rootCause = "ABNORMAL_DRAIN";
                    explanation = "Abnormal battery drain detected, likely due to " +
                            "background processes or app misbehavior.";
                    technicalDetails = primaryIssue.getStatement();
                    recommendations.add("Identify and address high-drain applications");
                    recommendations.add("Review background activity permissions");
                    engineerActions.add("Analyze wakelock patterns");
                    engineerActions.add("Profile top battery consumers");
                    userActions.add("Check battery usage in settings");
                    userActions.add("Restrict background activity for problematic apps");
                    break;
                    
                case "CHARGING_BEHAVIOR":
                    rootCause = "SUBOPTIMAL_CHARGING";
                    explanation = "Charging patterns may be contributing to accelerated " +
                            "battery wear. Habits affect long-term battery health.";
                    technicalDetails = primaryIssue.getStatement();
                    recommendations.add("Optimize charging habits for battery longevity");
                    engineerActions.add("Enable adaptive charging if available");
                    userActions.add("Avoid keeping device at 100% for extended periods");
                    userActions.add("Try to charge before reaching critically low levels");
                    break;
                    
                case "HEALTH_PATTERN":
                    rootCause = "NATURAL_DEGRADATION";
                    explanation = "Battery showing signs of normal wear consistent with age " +
                            "and usage. This is expected behavior.";
                    technicalDetails = primaryIssue.getStatement();
                    recommendations.add("Monitor capacity trends");
                    engineerActions.add("Log degradation rate for fleet analytics");
                    userActions.add("Plan for battery replacement if capacity drops below 80%");
                    break;
                    
                default:
                    rootCause = "GENERAL_WEAR";
                    explanation = primaryIssue.getStatement();
                    technicalDetails = "Multiple factors contributing to battery performance.";
                    recommendations.add("Continue monitoring battery metrics");
            }
            
            // Add contributing factors from other inferences
            for (AIInference inf : significantInferences) {
                if (inf != primaryIssue && inf.meetsMinimumConfidence()) {
                    contributing.add(inf.getInferenceType() + ": " + 
                            inf.getStatement().substring(0, Math.min(100, inf.getStatement().length())));
                }
            }
        }
        
        return new RootCauseAnalysis(
                rootCause,
                highestConfidence,
                contributing,
                significantInferences,
                explanation,
                technicalDetails,
                recommendations,
                engineerActions,
                userActions,
                deterministicData
        );
    }
    
