    /**
     * AI Inference - A single insight generated by AI with full evidence trail.
     */
    public static class AIInference {
        private final String inferenceType;           // What kind of inference
        private final String statement;               // The actual inference statement
        private final double confidenceScore;         // 0.0 - 1.0
        private final ConfidenceLevel confidenceLevel;
        private final List<String> evidenceCitations; // Data points supporting this
        private final List<String> caveats;           // Known limitations/uncertainties
        private final String methodology;             // How this was determined
        private final boolean actionable;             // Can user/engineer act on this?
        
        public AIInference(String inferenceType, String statement, double confidenceScore,
                           List<String> evidenceCitations, List<String> caveats,
                           String methodology, boolean actionable) {
            this.inferenceType = inferenceType;
            this.statement = statement;
            this.confidenceScore = Math.max(0, Math.min(1, confidenceScore));
            this.confidenceLevel = ConfidenceLevel.fromScore(this.confidenceScore);
            this.evidenceCitations = evidenceCitations != null ? evidenceCitations : new ArrayList<>();
            this.caveats = caveats != null ? caveats : new ArrayList<>();
            this.methodology = methodology;
            this.actionable = actionable;
        }
        
        public String getInferenceType() { return inferenceType; }
        public String getStatement() { return statement; }
        public double getConfidenceScore() { return confidenceScore; }
        public ConfidenceLevel getConfidenceLevel() { return confidenceLevel; }
        public List<String> getEvidenceCitations() { return evidenceCitations; }
        public List<String> getCaveats() { return caveats; }
        public String getMethodology() { return methodology; }
        public boolean isActionable() { return actionable; }
        
        public boolean meetsMinimumConfidence() {
            return confidenceScore >= MIN_CONFIDENCE_FOR_ASSERTION;
        }
        
        public boolean meetsRecommendationConfidence() {
            return confidenceScore >= MIN_CONFIDENCE_FOR_RECOMMENDATION;
        }
        
        public boolean meetsRootCauseConfidence() {
            return confidenceScore >= MIN_CONFIDENCE_FOR_ROOT_CAUSE;
        }
        
        public Map<String, Object> toMap() {
            Map<String, Object> map = new HashMap<>();
            map.put("type", inferenceType);
            map.put("statement", statement);
            map.put("confidence_score", confidenceScore);
            map.put("confidence_level", confidenceLevel.name());
            map.put("evidence_count", evidenceCitations.size());
            map.put("evidence", evidenceCitations);
            map.put("caveats", caveats);
            map.put("methodology", methodology);
            map.put("actionable", actionable);
            return map;
        }
    }
    
