    /**
     * Infer battery health pattern from deterministic data.
     * AI can interpret WHAT the pattern means, but exact values come from deterministic analysis.
     */
    private AIInference inferHealthPattern(List<BatterySnapshot> snapshots,
                                            Map<String, Object> deterministicData) {
        
        List<String> evidence = new ArrayList<>();
        List<String> caveats = new ArrayList<>();
        double confidenceScore = 0.5;  // Start at baseline
        
        // Analyze voltage behavior as health indicator
        @SuppressWarnings("unchecked")
        Map<String, Object> voltStats = (Map<String, Object>) deterministicData.get("voltage_stats");
        if (voltStats != null) {
            double minMv = getDouble(voltStats, "min_mv", 0);
            double maxMv = getDouble(voltStats, "max_mv", 0);
            double range = maxMv - minMv;
            
            evidence.add("Voltage range: " + String.format("%.0fmV - %.0fmV", minMv, maxMv));
            
            // Healthy battery shows good voltage range
            if (range > 500 && minMv > 3300 && maxMv < 4350) {
                confidenceScore += 0.15;
                evidence.add("Voltage behavior within healthy parameters");
            } else if (minMv < 3200) {
                confidenceScore += 0.10;
                evidence.add("Low minimum voltage observed indicating potential stress");
                caveats.add("Low voltage may be due to usage pattern, not necessarily health issue");
            }
        }
        
        // Analyze charge cycle impact
        @SuppressWarnings("unchecked")
        Map<String, Object> cycleData = (Map<String, Object>) deterministicData.get("charge_cycles");
        if (cycleData != null) {
            double cycles = getDouble(cycleData, "equivalent_cycles", 0);
            evidence.add("Equivalent charge cycles: " + String.format("%.1f", cycles));
            
            if (cycles < 100) {
                confidenceScore += 0.15;
                evidence.add("Low cycle count suggests battery is relatively new");
            } else if (cycles < 300) {
                confidenceScore += 0.10;
                evidence.add("Moderate cycle count within normal lifespan");
            } else {
                confidenceScore += 0.10;
                caveats.add("High cycle count - degradation expected");
            }
        }
        
        // Need minimum evidence
        if (evidence.size() < MIN_EVIDENCE_POINTS) {
            caveats.add("Limited data points for health assessment");
            confidenceScore *= 0.7;
        }
        
        // Build inference statement
        String statement;
        if (confidenceScore >= 0.75) {
            statement = "Battery health appears to be in good condition based on voltage " +
                    "behavior and cycle count. Normal degradation expected.";
        } else if (confidenceScore >= 0.60) {
            statement = "Battery health shows some wear indicators but remains functional. " +
                    "Monitor for changes.";
        } else {
            statement = "Insufficient data to confidently assess battery health. " +
                    "Continue monitoring.";
        }
        
        return new AIInference(
                "HEALTH_PATTERN",
                statement,
                confidenceScore,
                evidence,
                caveats,
                "Analysis of voltage range, cycle count, and degradation indicators",
                true
        );
    }
    
    /**
     * Infer usage pattern from drain and usage data.
     */
    private AIInference inferUsagePattern(List<BatterySnapshot> snapshots,
                                           List<DrainEvent> drainEvents,
                                           Map<String, Object> deterministicData) {
        
        List<String> evidence = new ArrayList<>();
        List<String> caveats = new ArrayList<>();
        double confidenceScore = 0.5;
        
        // Analyze screen time
        @SuppressWarnings("unchecked")
        Map<String, Object> timeDist = (Map<String, Object>) deterministicData.get("time_distribution");
        if (timeDist != null) {
            double screenOnPercent = getDouble(timeDist, "screen_on_percent", 0);
            double screenOnHours = getDouble(timeDist, "screen_on_time_hours", 0);
            
            evidence.add("Screen on time: " + String.format("%.1f hours (%.0f%%)", 
                    screenOnHours, screenOnPercent));
            
            if (screenOnPercent > 40) {
                confidenceScore += 0.15;
                evidence.add("Heavy screen usage pattern detected");
            } else if (screenOnPercent > 20) {
                confidenceScore += 0.15;
                evidence.add("Moderate screen usage pattern");
            } else {
                confidenceScore += 0.10;
                evidence.add("Light screen usage - device often idle");
            }
        }
        
        // Analyze drain rates
        @SuppressWarnings("unchecked")
        Map<String, Object> drainStats = (Map<String, Object>) deterministicData.get("drain_rate_stats");
        if (drainStats != null) {
            double meanDrain = getDouble(drainStats, "mean", 0);
            double maxDrain = getDouble(drainStats, "max", 0);
            
            evidence.add("Average drain rate: " + String.format("%.1f%%/hour", meanDrain));
            
            if (meanDrain > 10) {
                confidenceScore += 0.10;
                evidence.add("High power consumption pattern - heavy apps or gaming");
            } else if (meanDrain > 5) {
                confidenceScore += 0.15;
                evidence.add("Normal power consumption for active use");
            } else {
                confidenceScore += 0.15;
                evidence.add("Efficient power consumption pattern");
            }
        }
        
        // Build statement
        String usageType;
        if (confidenceScore >= 0.75) {
            usageType = "Power User";
        } else if (confidenceScore >= 0.65) {
            usageType = "Normal User";
        } else {
            usageType = "Light User";
        }
        
        String statement = "Usage pattern classification: " + usageType + ". " +
                "Based on screen time, drain rates, and activity patterns.";
        
        if (evidence.size() < MIN_EVIDENCE_POINTS) {
            caveats.add("Limited usage data available");
        }
        
        return new AIInference(
                "USAGE_PATTERN",
                statement,
                confidenceScore,
                evidence,
                caveats,
                "Analysis of screen time, drain rates, and activity metrics",
                true
        );
    }
    
    /**
     * Infer charging behavior patterns.
     */
    private AIInference inferChargingBehavior(List<ChargingSession> sessions,
                                               List<BatterySnapshot> snapshots,
                                               Map<String, Object> deterministicData) {
        
        List<String> evidence = new ArrayList<>();
        List<String> caveats = new ArrayList<>();
        double confidenceScore = 0.5;
        
        if (sessions.isEmpty()) {
            return new AIInference(
                    "CHARGING_BEHAVIOR",
                    "Insufficient charging session data for behavior analysis",
                    0.3,
                    evidence,
                    List.of("No charging sessions recorded"),
                    "Requires charging session data",
                    false
            );
        }
        
        // Analyze charging patterns
        int overnightCharges = 0;
        int quickCharges = 0;
        int deepDischargeCharges = 0;
        
        for (ChargingSession session : sessions) {
            // Check for overnight charging (> 6 hours)
            long durationMs = session.endTime - session.startTime;
            if (durationMs > TimeUnit.HOURS.toMillis(6)) {
                overnightCharges++;
            }
            
            // Quick charges (< 1 hour)
            if (durationMs < TimeUnit.HOURS.toMillis(1) && session.endLevel - session.startLevel > 20) {
                quickCharges++;
            }
            
            // Started charging at low battery
            if (session.startLevel < 20) {
                deepDischargeCharges++;
            }
        }
        
        evidence.add("Total charging sessions: " + sessions.size());
        evidence.add("Overnight charges: " + overnightCharges);
        evidence.add("Quick charges: " + quickCharges);
        evidence.add("Low battery charges: " + deepDischargeCharges);
        
        // Assess charging behavior health
        String behaviorAssessment;
        if (overnightCharges > sessions.size() * 0.5) {
            behaviorAssessment = "Frequent overnight charging detected - may contribute to " +
                    "battery wear over time";
            confidenceScore += 0.15;
            caveats.add("Modern devices often have charging optimization");
        } else if (deepDischargeCharges > sessions.size() * 0.3) {
            behaviorAssessment = "Frequent deep discharge before charging - " +
                    "moderate impact on battery longevity";
            confidenceScore += 0.15;
        } else {
            behaviorAssessment = "Charging patterns appear healthy for battery longevity";
            confidenceScore += 0.20;
        }
        
        return new AIInference(
                "CHARGING_BEHAVIOR",
                behaviorAssessment,
                confidenceScore,
                evidence,
                caveats,
                "Analysis of charging session duration, frequency, and start levels",
                true
        );
    }
    
