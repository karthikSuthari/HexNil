    /**
     * Perform comprehensive battery analysis with AI insights.
     * This is the main entry point for full AI-powered analysis.
     * 
     * ANTI-HALLUCINATION: Will return blocked result if data requirements not met.
     */
    public AIAnalysisOutput performComprehensiveAnalysis(
            @NonNull List<BatterySnapshot> snapshots,
            @NonNull List<ChargingSession> sessions,
            @NonNull List<DrainEvent> drainEvents,
            int chargeCycles,
            int fullCycles,
            double socCoverage) {
        
        Log.d(TAG, "Starting comprehensive AI analysis with " + snapshots.size() + 
              " snapshots, " + sessions.size() + " sessions, " + drainEvents.size() + " drain events");
        
        // Step 1: VALIDATE READINESS (Anti-hallucination gate)
        AIReadinessValidator.ReadinessResult readiness = 
                readinessValidator.validateComprehensiveAnalysisReadiness(
                        snapshots, sessions, drainEvents, chargeCycles, fullCycles, socCoverage);
        
        if (!readiness.isReady()) {
            Log.w(TAG, "AI analysis BLOCKED: " + readiness.getPrimaryBlocker());
            return createBlockedResult(readiness);
        }
        
        // Step 2: DETERMINISTIC CALCULATIONS (Exact values - no AI)
        Map<String, Object> deterministicResults = performDeterministicCalculations(
                snapshots, sessions, drainEvents);
        
        // Step 3: AI INTERPRETATIONS (Patterns, correlations, insights)
        List<AIInference> inferences = new ArrayList<>();
        Map<String, Object> interpretations = new HashMap<>();
        
        // Health pattern inference
        AIInference healthInference = inferHealthPattern(snapshots, deterministicResults);
        if (healthInference != null && healthInference.meetsMinimumConfidence()) {
            inferences.add(healthInference);
        }
        
        // Usage pattern inference
        AIInference usageInference = inferUsagePattern(snapshots, drainEvents, deterministicResults);
        if (usageInference != null && usageInference.meetsMinimumConfidence()) {
            inferences.add(usageInference);
        }
        
        // Charging behavior inference
        AIInference chargingInference = inferChargingBehavior(sessions, snapshots, deterministicResults);
        if (chargingInference != null && chargingInference.meetsMinimumConfidence()) {
            inferences.add(chargingInference);
        }
        
        // Thermal stress inference
        AIInference thermalInference = inferThermalStress(snapshots, deterministicResults);
        if (thermalInference != null && thermalInference.meetsMinimumConfidence()) {
            inferences.add(thermalInference);
        }
        
        // Drain anomaly inference
        AIInference drainInference = inferDrainAnomalies(drainEvents, snapshots, deterministicResults);
        if (drainInference != null && drainInference.meetsMinimumConfidence()) {
            inferences.add(drainInference);
        }
        
        // Step 4: ROOT CAUSE ANALYSIS (Synthesize all findings)
        RootCauseAnalysis rootCause = synthesizeRootCause(inferences, deterministicResults);
        
        // Step 5: IDENTIFY DATA LIMITATIONS
        List<String> limitations = identifyDataLimitations(snapshots, sessions, drainEvents);
        
        // Step 6: CALCULATE OVERALL CONFIDENCE
        double overallConfidence = calculateOverallConfidence(inferences, deterministicResults);
        
        // Store interpretations
        for (AIInference inf : inferences) {
            interpretations.put(inf.getInferenceType(), inf.toMap());
        }
        
        return new AIAnalysisOutput(
                true, readiness, rootCause, inferences,
                deterministicResults, interpretations,
                overallConfidence, limitations);
    }
    
    /**
     * Perform targeted analysis for a specific issue.
     */
    public AIAnalysisOutput performTargetedAnalysis(
            @NonNull String issueType,
            @NonNull List<BatterySnapshot> snapshots,
            @Nullable List<ChargingSession> sessions,
            @Nullable List<DrainEvent> drainEvents) {
        
        // Simpler validation for targeted analysis
        if (snapshots.size() < AIReadinessValidator.MIN_SNAPSHOTS_HEALTH_ANALYSIS / 2) {
            AIReadinessValidator.ReadinessResult blockedResult = 
                    new AIReadinessValidator.ReadinessResult(
                            false, issueType, new ArrayList<>(),
                            List.of("Insufficient data for " + issueType + " analysis"),
                            new HashMap<>(), 0.0, TimeUnit.HOURS.toMillis(4),
                            "Need more battery snapshots", "Continue collecting data");
            return createBlockedResult(blockedResult);
        }
        
        Map<String, Object> deterministicResults = new HashMap<>();
        List<AIInference> inferences = new ArrayList<>();
        
        switch (issueType.toUpperCase()) {
            case "RAPID_DRAIN":
                deterministicResults = performDrainCalculations(snapshots, drainEvents);
                AIInference drainInf = inferDrainAnomalies(
                        drainEvents != null ? drainEvents : new ArrayList<>(), 
                        snapshots, deterministicResults);
                if (drainInf != null) inferences.add(drainInf);
                break;
                
            case "THERMAL":
                deterministicResults = performThermalCalculations(snapshots);
                AIInference thermalInf = inferThermalStress(snapshots, deterministicResults);
                if (thermalInf != null) inferences.add(thermalInf);
                break;
                
            case "CHARGING":
                deterministicResults = performChargingCalculations(snapshots, sessions);
                AIInference chargingInf = inferChargingBehavior(
                        sessions != null ? sessions : new ArrayList<>(), 
                        snapshots, deterministicResults);
                if (chargingInf != null) inferences.add(chargingInf);
                break;
                
            case "HEALTH":
                deterministicResults = performHealthCalculations(snapshots);
                AIInference healthInf = inferHealthPattern(snapshots, deterministicResults);
                if (healthInf != null) inferences.add(healthInf);
                break;
                
            default:
                Log.w(TAG, "Unknown issue type: " + issueType);
        }
        
        RootCauseAnalysis rootCause = synthesizeRootCause(inferences, deterministicResults);
        double confidence = calculateOverallConfidence(inferences, deterministicResults);
        
        return new AIAnalysisOutput(true, null, rootCause, inferences,
                deterministicResults, new HashMap<>(), confidence, new ArrayList<>());
    }
    
