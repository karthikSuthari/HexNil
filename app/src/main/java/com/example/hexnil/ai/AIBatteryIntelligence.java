    // DETERMINISTIC CALCULATION METHODS (Delegated - No AI)
    // ═══════════════════════════════════════════════════════════════════════════════
    
    private Map<String, Object> performDeterministicCalculations(
            List<BatterySnapshot> snapshots,
            List<ChargingSession> sessions,
            List<DrainEvent> drainEvents) {
        
        Map<String, Object> results = new HashMap<>();
        
        // Temperature statistics
        DeterministicAnalyzer.DeterministicResult tempStats = 
                deterministicAnalyzer.calculateTemperatureStats(snapshots);
        if (tempStats.isValid()) {
            results.put("temperature_stats", tempStats.getOutputs());
        }
        
        // Voltage statistics
        DeterministicAnalyzer.DeterministicResult voltStats = 
                deterministicAnalyzer.calculateVoltageStats(snapshots);
        if (voltStats.isValid()) {
            results.put("voltage_stats", voltStats.getOutputs());
        }
        
        // SOC distribution
        DeterministicAnalyzer.DeterministicResult socDist = 
                deterministicAnalyzer.calculateSOCDistribution(snapshots);
        if (socDist.isValid()) {
            results.put("soc_distribution", socDist.getOutputs());
        }
        
        // Charge cycles
        DeterministicAnalyzer.DeterministicResult cycles = 
                deterministicAnalyzer.calculateChargeCycles(snapshots);
        if (cycles.isValid()) {
            results.put("charge_cycles", cycles.getOutputs());
        }
        
        // Time distribution
        DeterministicAnalyzer.DeterministicResult timeDist = 
                deterministicAnalyzer.calculateTimeDistribution(snapshots);
        if (timeDist.isValid()) {
            results.put("time_distribution", timeDist.getOutputs());
        }
        
        // Drain rate statistics
        if (!drainEvents.isEmpty()) {
            double[] drainRates = deterministicAnalyzer.extractDrainRates(drainEvents);
            if (drainRates.length > 0) {
                DeterministicAnalyzer.StatisticalSummary drainStats = 
                        deterministicAnalyzer.calculateStatistics(drainRates);
                results.put("drain_rate_stats", drainStats.toMap());
            }
        }
        
        // Level trend
        double[] levels = deterministicAnalyzer.extractLevels(snapshots);
        DeterministicAnalyzer.TrendResult levelTrend = 
                deterministicAnalyzer.calculateTrend(levels);
        Map<String, Object> trendMap = new HashMap<>();
        trendMap.put("trend_type", levelTrend.trendType);
        trendMap.put("slope", levelTrend.slope);
        trendMap.put("r_squared", levelTrend.rSquared);
        results.put("level_trend", trendMap);
        
        // Temperature-drain correlation
        if (snapshots.size() >= 10) {
            double[] temps = deterministicAnalyzer.extractTemperatures(snapshots);
            if (temps.length == levels.length && temps.length >= 3) {
                DeterministicAnalyzer.DeterministicResult correlation = 
                        deterministicAnalyzer.calculateCorrelation(temps, levels, "temperature", "level");
                if (correlation.isValid()) {
                    results.put("temp_level_correlation", correlation.getOutputs());
                }
            }
        }
        
        return results;
    }
    
    private Map<String, Object> performDrainCalculations(List<BatterySnapshot> snapshots,
                                                          List<DrainEvent> drainEvents) {
        Map<String, Object> results = new HashMap<>();
        
        if (drainEvents != null && !drainEvents.isEmpty()) {
            double[] drainRates = deterministicAnalyzer.extractDrainRates(drainEvents);
            if (drainRates.length > 0) {
                DeterministicAnalyzer.StatisticalSummary stats = 
                        deterministicAnalyzer.calculateStatistics(drainRates);
                results.put("drain_stats", stats.toMap());
            }
        }
        
        DeterministicAnalyzer.DeterministicResult timeDist = 
                deterministicAnalyzer.calculateTimeDistribution(snapshots);
        if (timeDist.isValid()) {
            results.put("time_distribution", timeDist.getOutputs());
        }
        
        return results;
    }
    
    private Map<String, Object> performThermalCalculations(List<BatterySnapshot> snapshots) {
        Map<String, Object> results = new HashMap<>();
        
        DeterministicAnalyzer.DeterministicResult tempStats = 
                deterministicAnalyzer.calculateTemperatureStats(snapshots);
        if (tempStats.isValid()) {
            results.put("temperature_stats", tempStats.getOutputs());
        }
        
        return results;
    }
    
    private Map<String, Object> performChargingCalculations(List<BatterySnapshot> snapshots,
                                                             List<ChargingSession> sessions) {
        Map<String, Object> results = new HashMap<>();
        
        if (sessions != null && !sessions.isEmpty()) {
            // Calculate charging rates for each session
            List<Double> rates = new ArrayList<>();
            for (ChargingSession session : sessions) {
                if (session.endTime > session.startTime && session.endLevel > session.startLevel) {
                    DeterministicAnalyzer.DeterministicResult rate = 
                            deterministicAnalyzer.calculateExactChargingRate(
                                    session.startLevel, session.endLevel,
                                    session.startTime, session.endTime);
                    if (rate.isValid()) {
                        Double rateValue = rate.getOutputDouble("charge_rate_per_hour", 0);
                        if (rateValue > 0) rates.add(rateValue);
                    }
                }
            }
            
            if (!rates.isEmpty()) {
                double[] rateArray = new double[rates.size()];
                for (int i = 0; i < rates.size(); i++) rateArray[i] = rates.get(i);
                DeterministicAnalyzer.StatisticalSummary stats = 
                        deterministicAnalyzer.calculateStatistics(rateArray);
                results.put("charging_rate_stats", stats.toMap());
            }
        }
        
        return results;
    }
    
    private Map<String, Object> performHealthCalculations(List<BatterySnapshot> snapshots) {
        Map<String, Object> results = new HashMap<>();
        
        DeterministicAnalyzer.DeterministicResult cycles = 
                deterministicAnalyzer.calculateChargeCycles(snapshots);
        if (cycles.isValid()) {
            results.put("charge_cycles", cycles.getOutputs());
        }
        
        DeterministicAnalyzer.DeterministicResult voltStats = 
                deterministicAnalyzer.calculateVoltageStats(snapshots);
        if (voltStats.isValid()) {
            results.put("voltage_stats", voltStats.getOutputs());
        }
        
        return results;
    }
    
